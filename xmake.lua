add_requires("quickjs")

add_rules("mode.debug", "mode.release")

target("peek")
    set_kind("binary")
    add_files("src/*.c")
    remove_files("src/gui.c", "src/dump.c")
    add_packages("quickjs")
    add_syslinks("mbedtls", "mbedx509", "mbedcrypto")
    set_rundir("$(projectdir)")

target("peekcss")
    set_kind("binary")
    add_files("src/dump.c", "src/html.c", "src/dom.c", "src/css.c", "src/net.c", "src/util.c", "src/scan.c")
    add_packages("quickjs")
    add_syslinks("mbedtls", "mbedx509", "mbedcrypto")
    set_rundir("$(projectdir)")

target("peekg")
    set_kind("binary")
    add_files("src/html.c", "src/dom.c", "src/css.c", "src/js.c", "src/net.c", "src/util.c", "src/ws.c", "src/scan.c", "src/gui.c")
    add_packages("quickjs")
    add_syslinks("mbedtls", "mbedx509", "mbedcrypto", "gtk-3", "gdk-3", "gobject-2.0", "glib-2.0", "gio-2.0", "pangocairo-1.0", "gdk_pixbuf-2.0", "cairo", "cairo-gobject", "pango-1.0")
    add_includedirs("/usr/include/gtk-3.0", "/usr/include/glib-2.0", "/usr/lib/glib-2.0/include", "/usr/include/pango-1.0", "/usr/include/cairo", "/usr/include/gdk-pixbuf-2.0", "/usr/include/atk-1.0", "/usr/include/harfbuzz", "/usr/include/libpng16", "/usr/include/freetype2", "/usr/include/fribidi", "/usr/include/pixman-1")
    add_cxflags("-Wno-deprecated-declarations")
    set_rundir("$(projectdir)")

target("check")
    set_kind("phony")
    add_deps("peek", "peekcss")
    on_run(function ()
        os.exec("sh tests/run.sh")
    end)
